function setLeaf(target: Record<string, unknown>, path: string, value: string): void {
  const parts = path.split('.')
  let cursor = target
  parts.slice(0, -1).forEach(part => {
    const child = cursor[part]
    if (!child || typeof child !== 'object' || Array.isArray(child)) cursor[part] = {}
    cursor = cursor[part] as Record<string, unknown>
  })
  cursor[parts[parts.length - 1]] = value
}

export function createCompatibilityLocale(label: (key: string) => string): Record<string, unknown> {
  const result: Record<string, unknown> = {}
  for (const key of keys) setLeaf(result, key, label(key))
  setLeaf(result, 'admin.groups.accountsUnit', 'accounts')
  return result
}

export function compatibilityLabel(key: string): string {
  const leaf = key.split('.').pop() || key
  return leaf.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/[-_]/g, ' ')
}
